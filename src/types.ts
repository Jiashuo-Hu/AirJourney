export type Place = {
  overrides?: string[];
  id: string;
  name: string;
  code?: string;
  city?: string;
  region?: string;
  lat?: number;
  lon?: number;
  zone?: string;
  aliases?: string;
  hidden?: boolean;
  source?: string;
};
export type Reference = Place & {
  alliance?: string;
  logo?: string;
  manufacturer?: string;
  family?: string;
};
export type TimeSpec = { date: string; time: string; zone: string };
export type Flight = {
  id: string;
  created: string;
  updated: string;
  number: string;
  from: Place;
  to: Place;
  airline?: Reference;
  aircraft?: Reference;
  alliance?: string;
  allianceLogo?: string;
  departure: TimeSpec;
  arrival: TimeSpec;
  distance?: number;
  unit: "km" | "miles";
  duration?: number;
  status: "Recorded" | "Planned" | "Draft";
  tags: string[];
  notes: string;
  fields: Record<string, string>;
  color: string;
  visible: boolean;
  deleted?: string;
};
export type Field = {
  id: string;
  label: string;
  type: "text" | "number" | "date" | "select";
  options: string;
  hidden: boolean;
};
export type Settings = {
  theme: string;
  accent: string;
  units: "km" | "miles";
  dateFormat: string;
  clock: string;
  density: string;
  routeColor: string;
  width: number;
  opacity: number;
  markerSize: number;
  labels: boolean;
  boundaries: boolean;
  reducedMotion: boolean;
  sidebarWidth: number;
  home: number[];
  remember: boolean;
  lastView?: number[];
  mapImage?: string;
  mapSource?: string;
};
export type State = {
  schema: 1;
  flights: Flight[];
  library: Record<string, Reference[]>;
  fields: Field[];
  tags: string[];
  settings: Settings;
};
